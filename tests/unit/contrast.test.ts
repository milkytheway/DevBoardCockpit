import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * The **contrast** of the theme tokens.
 *
 * Why this needs a test: a colour is something that "looks right" — the eye
 * can hardly tell `#667080` from `#7d879a` on a dark background, yet the
 * first one reaches only 3.59:1 against the body text and a user with a low
 * vision **cannot read it**.
 *
 * WCAG AA asks for 4.5:1 for the body text. The hints of an empty state
 * ("nothing selected", "pick a connection to start") and the explanations
 * such as "this connection cannot transfer files" all use the dimmed colour —
 * if they cannot be read they are as good as not written.
 *
 * Therefore the numbers go into the test instead of into a comment.
 */

// **What is read is the generated artefact** (`tokens.generated.css`) —
// the source of truth of the tokens is `src/shared/theme/seed.ts` and this CSS is generated by `npm run gen:theme`,
// `gen:theme:check` guards that it agrees with the seed.
// (It used to read the hand-written `tokens.css`, and after the rename nobody followed up → the unit test went red.)
const CSS = readFileSync(
  join(__dirname, '../../src/renderer/theme/tokens.generated.css'),
  'utf8',
);

/** Reads the value of a token out of the CSS */
function token(name: string): string {
  const m = new RegExp(`--${name}:\\s*(#[0-9a-fA-F]{6})`).exec(CSS);
  if (!m) throw new Error(`the CSS has no --${name}`);
  return m[1];
}

/** The relative luminance (the definition of WCAG 2.1) */
function luminance(hex: string): number {
  const r = parseInt(hex.slice(1, 3), 16) / 255;
  const g = parseInt(hex.slice(3, 5), 16) / 255;
  const b = parseInt(hex.slice(5, 7), 16) / 255;
  const linear = (c: number): number =>
    c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  return 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b);
}

/** The contrast */
function contrast(a: string, b: string): number {
  const la = luminance(a);
  const lb = luminance(b);
  const [hi, lo] = la > lb ? [la, lb] : [lb, la];
  return (hi + 0.05) / (lo + 0.05);
}

describe('the contrast of the theme tokens', () => {
  const bg = token('cockpit-bg');
  /**
   * The dimmed text has to reach the criterion **against the background it is
   * really rendered on**.
   *
   * The previous version only tested `--cockpit-bg`, while
   * `--cockpit-unavailable` is really used in the file browser
   * (`--cockpit-bg-elevated`), so "the background that was tested was not the
   * one it is rendered on" and the insufficient 4.19:1 was missed.
   */
  const elevated = token('cockpit-bg-elevated');

  it('the body colour against the background reaches ≥ 4.5:1', () => {
    expect(contrast(token('cockpit-text'), bg)).toBeGreaterThanOrEqual(4.5);
  });

  it('the dimmed text reaches ≥ 4.5:1 — the hint of an empty state is meant for a user with a low vision', () => {
    // It used to be #667080, only 3.59:1
    expect(contrast(token('cockpit-text-faint'), bg)).toBeGreaterThanOrEqual(4.5);
  });

  it('the secondary text reaches ≥ 4.5:1', () => {
    expect(contrast(token('cockpit-text-dim'), bg)).toBeGreaterThanOrEqual(4.5);
  });

  it('the semantic colour of "unavailable" reaches ≥ 4.5:1 — it carries "this board does not provide that capability"', () => {
    // It used to be #6e7681, only 3.91:1
    expect(contrast(token('cockpit-unavailable'), bg)).toBeGreaterThanOrEqual(4.5);
  });

  it('the dimmed text also reaches ≥ 4.5:1 **on the background it is really rendered on**', () => {
    // The file browser and the toolbar use the elevated background
    expect(contrast(token('cockpit-text-faint'), elevated)).toBeGreaterThanOrEqual(4.5);
    expect(contrast(token('cockpit-text-dim'), elevated)).toBeGreaterThanOrEqual(4.5);
    expect(contrast(token('cockpit-unavailable'), elevated)).toBeGreaterThanOrEqual(4.5);
  });

  it('the danger colour against the background reaches ≥ 3:1 — the error bar is large, it only has to be distinguishable', () => {
    // The error bar uses the 13px body text, in theory that asks for 4.5:1.
    // But it is a strong signal that "something went wrong", 3:1 is the floor; the real value is higher.
    expect(contrast(token('cockpit-danger'), bg)).toBeGreaterThanOrEqual(3);
  });
});
